@app.cell(hide_code=True)
def text_idea():
    mo.vstack([
        mo.md(r"""
        ## The idea

        A **chatbot** is a program you can have a conversation with in ordinary language. ELIZA's rules are not in the program but in a **script**; in Weizenbaum's words, "a script is data; i.e., it is not part of the program itself." The best-known script, DOCTOR, makes ELIZA answer like a psychotherapist, who can ask about anything without knowing anything about it. For each line the user types, the program of 1965 takes these steps:

        1. **Words.** The line becomes a list of words in capitals; a period and a comma are words of their own.
        2. **One part.** At a period, a comma or *but*, ELIZA drops the part before it when that part holds no keyword; otherwise it drops the rest. What stays is the first part with a keyword, or else the last part.
        3. **Swaps.** A word of the script can have a substitute: `(ME = YOU)` swaps *me* for *you*. The DOCTOR script swaps *I* and *you*, *my* and *your*, *am* and *are*, and *was* and *were*, so that ELIZA can hand a sentence back.
        4. **The keyword.** A word of the script with rules is a **keyword**. A few keywords have a **rank**: *always* 1, *everybody*, *everyone*, *nobody* and *noone* 2, and *if* 3; the others have rank 0. The keyword with the highest rank wins, the first one on a tie.
        5. **Decomposition.** Each keyword has **decomposition rules**, which ELIZA tries in order; they are written with the swapped words. Weizenbaum: "The "0" in the decomposition rule stands for "an indefinite number of words"". So `(0 YOUR 0)` fits any text with *YOUR* in it and cuts it into three parts: the words before *YOUR*, *YOUR* itself, and the words after it. Every `0` but the last takes as few words as it can; the last takes the rest. A slash in parentheses, `(/FAMILY)`, fits any word the script tags as family, such as *MOTHER*, and `(=WHAT)` sends ELIZA on to the rules of *WHAT*.
        6. **Reassembly.** Each decomposition rule has **reassembly rules**: `(YOUR 3)` gives *YOUR* followed by the words of part 3. The reassembly rules of one decomposition rule take turns; in Weizenbaum's words, "This mechanism insures that the complete set of reassembly rules associated with a given decomposition rule is cycled through before any repetitions occur."
        7. **No keyword.** ELIZA then says a line of the special keyword NONE, such as *PLEASE GO ON*, or a memory. Each time *MY* is the keyword, one of four memory rules turns the text into a sentence for later, such as *EARLIER YOU SAID YOUR ...*; a hash of the last word decides which rule. When a line has no keyword and a counter in the program is at 4 (it counts 1, 2, 3, 4 and starts again, one step per line), ELIZA says its oldest memory instead.

        **The program of 1965.** For decades only the paper was known. In 2021, Jeff Shrager and the archivist Myles Crowley found a printout of the program in Weizenbaum's papers at MIT, with the DOCTOR script attached, and Weizenbaum's estate released it under CC0, so anyone may use it. Anthony Hay and Arthur Schwarz typed the code in from the printout, and with Rupert Lane got it running again on CTSS, the time-sharing system of MIT in the 1960s, in an emulator of its IBM 7094 computer. Their run of the paper's conversation is the course's reference. The script of 1965 differs a little from the paper's: to *Men are all alike.* it answers *DID YOU THINK THEY MIGHT NOT BE ALL ALIKE*, not *IN WHAT WAY*. The course's own Python version of the program gives the same 15 replies as that run. The course changed one word of the conversation: line 4 starts with *They*, where the run has a pronoun for one person; neither word is in the script, so the reply stays the same.

        **More scripts, more chatbots.** Weizenbaum wrote that scripts existed "in Welsh and German as well as in English"; the Dutch lesson has a script of the course's own. Rule-based chatbots went on after ELIZA. Richard Wallace's A.L.I.C.E., first written in 1995, won the Loebner Prize, a yearly contest built on the Turing test, in 2000 and 2001. Its rules are in AIML, and Wallace wrote: "The basic unit of knowledge in AIML is called a category." A category has a pattern with wildcards, such as `I AM *`, and a template for the reply: a decomposition rule and a reassembly rule by other names.

        **The ELIZA effect.** Douglas Hofstadter (1995) used and defined a name for what ELIZA showed, the **ELIZA effect**: "the susceptibility of people to read far more understanding than is warranted into strings of symbols — especially words — strung together by computers."

        The picture follows line 3 of the conversation through the steps.
        """),
    ])
    return


