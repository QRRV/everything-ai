@app.cell(hide_code=True)
def text_idea():
    mo.md(r"""
    ## The idea

    *What NLP is* named the side of NLP that makes text: **natural language generation** (NLG). This lesson is about **data-to-text generation**, where what goes in is data, such as a table of numbers. Ehud Reiter, who built such systems at the University of Aberdeen, wrote in 1996: "From a technical perspective, almost all applied NLG systems perform the following three tasks". This lesson calls them:

    1. **Content selection** decides what to say. A table holds more than a reader needs, and the program keeps what matters as **messages**, such as *6.5 mm of rain on Wednesday*, and puts them in order. Gatt and Krahmer: "Typically, more information is contained in data than we want to convey through text, or the data is more detailed than we care to express in text."
    2. **Microplanning** plans the sentences. It chooses the words for each message, such as *windy* for wind force 6; it decides which messages share a sentence, called **aggregation**; and it decides how to refer to something that the text already named.
    3. **Surface realization** writes each sentence out by the rules of its language: the order of the words, their endings, the commas and the period.

    Reiter called the three "Content Determination and Text Planning", "Sentence Planning" and "Realization". In the book that Reiter wrote with Robert Dale in 2000, they are document planning, microplanning and realization, and Sripada and colleagues describe SumTime-Mousam in those three stages. Gatt and Krahmer split the same work into six tasks: content determination and text structuring make up the first stage, which they call the text planner; sentence aggregation, lexicalization and referring expression generation make up microplanning; and linguistic realization is surface realization. This lesson names the first step after its main task, choosing the content.

    The picture shows the three steps on a week in April that the course made up.
    """)
    return


